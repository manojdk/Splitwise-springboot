-- Step 4: activity feed / audit trail. One row per change, written in the same transaction as the change,
-- so the history can never disagree with the data.
--
-- Visibility: a group's activity is visible to the group's current members; activity_user additionally lists
-- the people involved (payer, participants, the member added or removed), who keep seeing "their" events even
-- after leaving the group. Non-group activity is visible only through activity_user.

CREATE TABLE activity (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type          VARCHAR(30)              NOT NULL,
    actor_id      BIGINT                   NOT NULL REFERENCES app_user (id),
    -- A deleted group takes its history with it (GROUP_DELETED itself is stored without a group)
    group_id      BIGINT REFERENCES expense_group (id) ON DELETE CASCADE,
    expense_id    BIGINT REFERENCES expense (id),
    settlement_id BIGINT REFERENCES settlement (id),
    summary       VARCHAR(500)             NOT NULL,
    details       VARCHAR(4000),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_activity_group ON activity (group_id, id);
CREATE INDEX idx_activity_expense ON activity (expense_id);

CREATE TABLE activity_user (
    activity_id BIGINT NOT NULL REFERENCES activity (id) ON DELETE CASCADE,
    user_id     BIGINT NOT NULL REFERENCES app_user (id),
    PRIMARY KEY (activity_id, user_id)
);

CREATE INDEX idx_activity_user_user ON activity_user (user_id);
