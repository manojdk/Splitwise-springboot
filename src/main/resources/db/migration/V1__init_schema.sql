-- Initial schema. Table names avoid reserved words (user, group).

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)             NOT NULL,
    email         VARCHAR(255)             NOT NULL,
    password_hash VARCHAR(100)             NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_app_user_email UNIQUE (email)
);

CREATE TABLE expense_group (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)             NOT NULL,
    created_by BIGINT                   NOT NULL REFERENCES app_user (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE group_member (
    group_id BIGINT NOT NULL REFERENCES expense_group (id) ON DELETE CASCADE,
    user_id  BIGINT NOT NULL REFERENCES app_user (id),
    PRIMARY KEY (group_id, user_id)
);

CREATE INDEX idx_group_member_user ON group_member (user_id);

CREATE TABLE expense (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description  VARCHAR(255)             NOT NULL,
    amount       NUMERIC(19, 2)           NOT NULL CHECK (amount > 0),
    currency     VARCHAR(3)               NOT NULL,
    paid_by      BIGINT                   NOT NULL REFERENCES app_user (id),
    group_id     BIGINT REFERENCES expense_group (id),
    expense_date DATE                     NOT NULL,
    split_type   VARCHAR(20)              NOT NULL,
    created_by   BIGINT                   NOT NULL REFERENCES app_user (id),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_expense_group ON expense (group_id);
CREATE INDEX idx_expense_paid_by ON expense (paid_by);

CREATE TABLE expense_share (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id BIGINT         NOT NULL REFERENCES expense (id) ON DELETE CASCADE,
    user_id    BIGINT         NOT NULL REFERENCES app_user (id),
    amount     NUMERIC(19, 2) NOT NULL CHECK (amount >= 0),
    CONSTRAINT uk_expense_share_user UNIQUE (expense_id, user_id)
);

CREATE INDEX idx_expense_share_user ON expense_share (user_id);

CREATE TABLE settlement (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer_id   BIGINT                   NOT NULL REFERENCES app_user (id),
    payee_id   BIGINT                   NOT NULL REFERENCES app_user (id),
    amount     NUMERIC(19, 2)           NOT NULL CHECK (amount > 0),
    currency   VARCHAR(3)               NOT NULL,
    group_id   BIGINT REFERENCES expense_group (id),
    settled_on DATE                     NOT NULL,
    note       VARCHAR(255),
    created_by BIGINT                   NOT NULL REFERENCES app_user (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_settlement_distinct_users CHECK (payer_id <> payee_id)
);

CREATE INDEX idx_settlement_group ON settlement (group_id);
CREATE INDEX idx_settlement_payer ON settlement (payer_id);
CREATE INDEX idx_settlement_payee ON settlement (payee_id);
