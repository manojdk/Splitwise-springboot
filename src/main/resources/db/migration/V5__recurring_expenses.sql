-- Step 5: recurring expenses (rent, wifi, subscriptions).
--
-- A template describes the expense and how often it repeats. A scheduled job creates a real expense for every
-- due date. Occurrence n falls on start_date + n periods (computed from the start each time, so a monthly
-- expense starting on the 31st is on the 28th/29th in February and back on the 31st in March).
-- The unique (recurring_expense_id, occurrence_date) on expense makes creating the same occurrence twice
-- impossible, even with several app instances.

CREATE TABLE recurring_expense (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id         BIGINT REFERENCES expense_group (id) ON DELETE CASCADE,
    description      VARCHAR(255)             NOT NULL,
    amount           NUMERIC(19, 2)           NOT NULL CHECK (amount > 0),
    currency         VARCHAR(3)               NOT NULL,
    paid_by          BIGINT                   NOT NULL REFERENCES app_user (id),
    split_type       VARCHAR(20)              NOT NULL,
    category         VARCHAR(30)              NOT NULL,
    notes            VARCHAR(1000),
    frequency        VARCHAR(10)              NOT NULL,
    start_date       DATE                     NOT NULL,
    end_date         DATE,
    next_occurrence  INTEGER                  NOT NULL DEFAULT 0,
    next_run_date    DATE,
    active           BOOLEAN                  NOT NULL,
    stopped_reason   VARCHAR(255),
    created_by       BIGINT                   NOT NULL REFERENCES app_user (id),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT ck_recurring_frequency CHECK (frequency IN ('WEEKLY', 'MONTHLY', 'YEARLY')),
    CONSTRAINT ck_recurring_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE INDEX idx_recurring_due ON recurring_expense (active, next_run_date);

CREATE TABLE recurring_expense_share (
    recurring_expense_id BIGINT NOT NULL REFERENCES recurring_expense (id) ON DELETE CASCADE,
    user_id              BIGINT NOT NULL REFERENCES app_user (id),
    split_value          NUMERIC(19, 4),
    PRIMARY KEY (recurring_expense_id, user_id)
);

ALTER TABLE expense ADD COLUMN recurring_expense_id BIGINT;
ALTER TABLE expense ADD COLUMN occurrence_date DATE;
ALTER TABLE expense ADD CONSTRAINT fk_expense_recurring FOREIGN KEY (recurring_expense_id)
    REFERENCES recurring_expense (id) ON DELETE SET NULL;
ALTER TABLE expense ADD CONSTRAINT uk_expense_occurrence UNIQUE (recurring_expense_id, occurrence_date);
